def build_local_page_text(bundle: dict[str, Any]) -> str:
    dish_name = bundle.get("dish_name", "这道菜")
    notes = bundle.get("notes", "")
    has_sour_direction = contains_any(notes, ["酸", "柠檬", "冬阴功", "番茄", "梅子"]) 
    has_spicy_direction = contains_any(notes, ["辣", "小米辣", "干辣椒", "花椒", "豆瓣"]) 

    sour_card = (
        "【内容卡1】\n"
        "标题：想更酸亮一点\n"
        "1. 起锅前补 2 到 3 片柠檬片 或 8ml 柠檬汁 酸感会更立起来\n"
        "2. 想酸得更干净 用现挤柠檬汁 想酸得更集中 可少量用浓缩柠檬液\n"
        "3. 这类加法更适合本身就带酸香方向的菜 不要把主体味型冲散\n"
    ) if has_sour_direction else (
        "【内容卡1】\n"
        "标题：想更酱香更厚一点\n"
        "1. 黄豆酱可再加 5g 老抽再补 2ml 味道会更浓更下饭\n"
        "2. 这类加法适合重口饭搭子路线 但别一次加太猛\n"
        "3. 想保住层次 就让酱香更厚 不是只会一味加盐\n"
    )

    spicy_card = (
        "【内容卡2】\n"
        "标题：想更辣有两条路\n"
        "1. 想要炝辣感 用 4 到 6g 干辣椒段热油激一下\n"
        "2. 想要鲜辣感 用 8 到 12g 小米辣碎 后段再加会更直给\n"
        "3. 两种辣感可以叠 但第一次建议先走一条线\n"
    ) if has_spicy_direction else (
        "【内容卡2】\n"
        "标题：想更辣也能往上推\n"
        "1. 起锅前加 5g 刀口辣椒 辣感更香更厚\n"
        "2. 想要更直接的鲜辣口 就补 8g 小米辣碎\n"
        "3. 这道菜底子偏咸香 辣度上去后会更适合拌饭\n"
    )

    return f"""
【页面信息】
页码：06/06
页面名称：口味调整
页面标题：按自己口味往上调
页面副标题：同一锅底 还能调出不同风味
阅读收益：滑到最后这一张 你就知道怎么把 {dish_name} 调成自己最喜欢的版本

{sour_card}

{spicy_card}

【内容卡3】
标题：想更清爽也有办法
1. 勾芡量减一点 葱花量多一点 整体会更轻快不糊口
2. 老抽减 2ml 留住酱香但别让颜色压太深
3. 如果想更适合夏天吃 就让浓度收住七八分 不一定非要很厚

【页尾提示】
真正会做的人 不是只会照配方做 而是知道怎么把 {dish_name} 调成自己最爱的味道
""".strip()
